// LOGIC TO APPLY TRANSLATIONS
// ============================================

(function() {
    const langBtn = document.querySelector('.lang-btn .current-lang');
    const langDropdown = document.querySelector('.lang-dropdown');
    const mobileLangButtons = document.querySelectorAll('.mobile-lang-selector button');

    // Get saved language or default to French
    let currentLang = localStorage.getItem('flc_lang') || 'fr';

    function updateTexts(lang) {
        const elements = document.querySelectorAll('[data-i18n]');

        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');

            if (translations[lang] && translations[lang][key]) {
                // Some translations intentionally contain HTML such as <strong>
                el.innerHTML = translations[lang][key];
            }
        });

        // Update active state in dropdowns
        document.querySelectorAll('.lang-dropdown button').forEach(btn => {
            btn.classList.toggle('active', btn.dataset.lang === lang);
        });

        mobileLangButtons.forEach(btn => {
            btn.classList.toggle('active', btn.dataset.lang === lang);
        });

        if (langBtn) {
            langBtn.textContent = lang.toUpperCase();
        }

        // Save preference
        localStorage.setItem('flc_lang', lang);
        currentLang = lang;

        // Update HTML lang attribute
        document.documentElement.lang = lang;
    }

    // Initialize
    updateTexts(currentLang);

    // Desktop Dropdown Events
    if (langDropdown) {
        langDropdown.addEventListener('click', (e) => {
            if (e.target.tagName === 'BUTTON') {
                const newLang = e.target.dataset.lang;

                if (newLang && newLang !== currentLang) {
                    updateTexts(newLang);
                }
            }
        });
    }

    // Mobile Selector Events
    mobileLangButtons.forEach(btn => {
        btn.addEventListener('click', () => {
            const newLang = btn.dataset.lang;

            if (newLang && newLang !== currentLang) {
                updateTexts(newLang);
            }
        });
    });

})();